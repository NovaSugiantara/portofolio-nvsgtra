/**
 * Writes supabase/seed.sql from the static content in portfolio/server/data/portfolio.ts,
 * so the database starts with exactly what the site shows today.
 *
 * Run from the repo root: node supabase/scripts/generate-seed.ts
 * (Node 22.18+ strips the TypeScript types natively.)
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { profile, projects } from '../../portfolio/server/data/portfolio.ts'

const text = (value: string | null | undefined) =>
  value == null ? 'null' : `'${value.replaceAll("'", "''")}'`
const textArray = (values: string[]) =>
  values.length ? `array[${values.map(text).join(', ')}]::text[]` : `'{}'::text[]`
const json = (value: unknown) => (value == null ? 'null' : `${text(JSON.stringify(value))}::jsonb`)

const profileSql = `insert into public.site_profiles (
  site, full_name, headline, summary, location, email, linkedin_url, website_url,
  hero_media, hero_video_url, hero_poster_url, avatar_url, avatar_alt
) values (
  'portfolio', ${text(profile.full_name)}, ${text(profile.headline)}, ${text(profile.summary)},
  ${text(profile.location)}, ${text(profile.email)}, ${text(profile.linkedin_url)}, ${text(profile.website_url)},
  'video', '/video/hero-bg.webm', '/video/hero-poster.webp', ${text(profile.avatar_url)}, null
) on conflict (site) do nothing;`

const projectSql = projects.map((project) => `insert into public.projects (
  site, slug, kind, title, summary, description, contributions, team_note, tech_stack, role,
  project_url, project_url_label, repo_url, cover_image_url, cover_alt, challenge, is_published, sort_order
) values (
  'portfolio', ${text(project.slug)}, ${text(project.kind)}, ${text(project.title)}, ${text(project.summary)},
  ${text(project.description)}, ${textArray(project.contributions)}, ${text(project.team_note)},
  ${textArray(project.tech_stack)}, ${text(project.role)}, ${text(project.project_url)},
  ${text(project.project_url_label)}, ${text(project.repo_url)}, ${text(project.cover_image_url)},
  ${text(project.cover_alt)}, ${json(project.challenge)}, true, ${project.sort_order}
) on conflict (site, slug) do nothing;`).join('\n\n')

const output = `-- Generated by supabase/scripts/generate-seed.ts. Do not edit by hand.
-- Public content only: everything here is already visible on novasugiantara.web.id.

${profileSql}

${projectSql}
`

writeFileSync(fileURLToPath(new URL('../seed.sql', import.meta.url)), output)
console.log(`seed.sql written: 1 profile, ${projects.length} projects`)
